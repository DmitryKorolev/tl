# shellcheck shell=sh
# Shared release-machinery helpers. Sourced, never executed.
#
#   . "$(dirname -- "$0")/lib/release-common.sh"
#
# Before this file, `sha256_of`, the SHA256SUMS line lookup, the uname-to-target
# mapping, the ADR-0006 tier lists, the stub cosign and the selftest reporting
# harness each existed three to five times across the release scripts, and had
# already diverged in what they accepted and what they said when they refused.
# A digest helper that is correct in one copy and wrong in another is worse than
# either, because the divergence is invisible at the call site.
#
# `install.sh` deliberately does *not* source this. It is piped straight into a
# shell with no checkout to read, so it carries embedded copies of the few
# helpers it needs; `scripts/check-embedded-copies.sh` fails if those drift from
# the definitions here, the same discipline the signing pin already follows.
#
# Every function is prefixed `rc_` and every variable `RC_`/`rc_`, so a sourcing
# script can tell at a glance what came from here.

# The repository root, derived from this file's own location rather than from
# the caller's working directory: the scripts that source it are run from CI,
# from a checkout, and from inside their own throwaway fixtures.
RC_LIB_DIR=$(CDPATH='' cd -- "$(dirname -- "${RC_LIB_SELF:-$0}")" && pwd -P)
case $RC_LIB_DIR in
  */scripts/lib) RC_ROOT=$(CDPATH='' cd -- "$RC_LIB_DIR/../.." && pwd -P) ;;
  */scripts) RC_ROOT=$(CDPATH='' cd -- "$RC_LIB_DIR/.." && pwd -P) ;;
  *) RC_ROOT=$RC_LIB_DIR ;;
esac

# ---------------------------------------------------------------------------
# Digests
#
# One definition, because the two copies this replaces disagreed: both accepted
# uppercase hex from a sums file and then compared it case-sensitively against
# their own always-lowercase output, so a valid `SHA256SUMS` regenerated by a
# tool that emits uppercase (Windows `certutil`, some mirror tooling) was
# reported to the user as tampering. Digests are normalized to lowercase here,
# at the one place that produces and the one place that reads them.
# ---------------------------------------------------------------------------

# Lowercase a hex string without spawning tr on every call in the hot path.
rc_lower() {
  printf '%s' "$1" | tr 'ABCDEF' 'abcdef'
}

# SHA-256 of a file, lowercase hex. coreutils ships sha256sum; macOS ships
# shasum. Both print "<hex>  <name>", so the first field is the digest.
#
# Deliberately not `sha256sum "$1" | cut -d' ' -f1`. A pipeline's status is its
# *last* command's, so `cut` returning 0 masked a digest tool that was present
# on PATH but broken — the caller got an empty string and a success status, and
# reported it downstream as "the file hashes to  but SHA256SUMS says …", which
# is a tampering verdict for a broken toolchain. Substitution first, status
# checked, field taken afterwards.
rc_sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    rc__digest_out=$(sha256sum "$1") || rc__digest_out=''
  elif command -v shasum >/dev/null 2>&1; then
    rc__digest_out=$(shasum -a 256 "$1") || rc__digest_out=''
  else
    echo "no sha256sum or shasum on PATH — the digest check is mandatory and cannot be skipped. Install coreutils (Linux) or use the system shasum (macOS)." >&2
    return 1
  fi
  if [ -z "$rc__digest_out" ]; then
    echo "the digest tool on PATH produced no output for '$1' — it is present but not working. The digest check is mandatory and cannot be skipped; repair the installation of coreutils or shasum." >&2
    return 1
  fi
  printf '%s' "${rc__digest_out%% *}"
}

# Pull one asset's digest out of a sums file by exact name, and prove it is a
# digest before anybody compares against it.
#
# Not `sha256sum -c`, which checks every line and so fails on assets for other
# platforms that were never downloaded. The `*name` form is accepted because
# that is what `sha256sum` writes in binary mode.
#
# Prints the lowercase digest on success. On failure prints a teaching message
# to stderr and returns non-zero; the caller decides whether that is fatal.
rc_sums_digest() {
  rc__sums=$1
  rc__name=$2
  if ! rc__digest=$(awk -v want="$rc__name" \
      '$2 == want || $2 == "*" want { print $1; found = 1 } END { exit !found }' "$rc__sums"); then
    echo "$rc__sums has no entry named '$rc__name'. Either the asset was renamed after signing, or this is a different release's sums file." >&2
    return 1
  fi
  case $rc__digest in
    *[!0-9a-fA-F]* | '')
      echo "the $rc__sums entry for '$rc__name' is not a hex digest ('$rc__digest') — the file is malformed or truncated; re-download it." >&2
      return 1
      ;;
  esac
  if [ "${#rc__digest}" -ne 64 ]; then
    echo "the $rc__sums entry for '$rc__name' is ${#rc__digest} characters, not the 64 of a SHA-256 digest — the file is malformed or truncated; re-download it." >&2
    return 1
  fi
  rc_lower "$rc__digest"
}

# ---------------------------------------------------------------------------
# Platform detection
#
# One mapping, one set of refusals. The npm launcher keeps its own copy because
# it ships inside a package that has no access to this repository; the installer
# keeps its own because it is piped from curl. Both are drift-guarded.
# ---------------------------------------------------------------------------

# Sets RC_OS. Returns 1 with a teaching message on an unsupported system.
#
# Nothing in this repository calls it, and that is the point: the two consumers
# that need the mapping — install.sh and the npm launcher — cannot source this
# file, so what lives here is the *reference* their copies are compared against
# by scripts/check-embedded-copies.sh, which reads it as text. RC_OS therefore
# has no reader in shell, which is what SC2034 is reporting.
# shellcheck disable=SC2034
rc_detect_os() {
  case $(uname -s) in
    Darwin) RC_OS=darwin ;;
    Linux) RC_OS=linux ;;
    MINGW* | MSYS* | CYGWIN* | Windows_NT)
      echo "native Windows is not supported — tl's filesystem primitives are unimplemented there, so a binary would start but could not safely create or mutate task state. Use WSL2, where the Linux x86-64 build runs and is fully supported." >&2
      return 1
      ;;
    *)
      echo "unsupported operating system '$(uname -s)'. tl publishes binaries for Linux and macOS only; to use it elsewhere, build from source with Lean 4." >&2
      return 1
      ;;
  esac
}

# Sets RC_ARCH. The reference for the shipped copies, as above.
# shellcheck disable=SC2034
rc_detect_arch() {
  case $(uname -m) in
    arm64 | aarch64) RC_ARCH=arm64 ;;
    x86_64 | amd64) RC_ARCH=x64 ;;
    *)
      echo "unsupported CPU architecture '$(uname -m)'. tl publishes arm64 and x86-64 binaries; to use it elsewhere, build from source with Lean 4." >&2
      return 1
      ;;
  esac
}

