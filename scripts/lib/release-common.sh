# ---------------------------------------------------------------------------
# Targets and ADR-0006 support tiers, from release/targets.json
#
# The tier split decides whether a missing binary is a warning or a refusal, and
# it decided that independently in npm-pack.sh, gen-homebrew-formula.sh and the
# release workflow. One source now, so "Supported" cannot mean three things.
# ---------------------------------------------------------------------------

RC_TARGETS_FILE=${RC_TARGETS_FILE:-"$RC_ROOT/release/targets.json"}

# rc_targets [tier] — space-separated target names, in file order. With no
# argument, every target; with `supported` or `best-effort`, that tier only.
rc_targets() {
  rc__tier=${1-}
  [ -f "$RC_TARGETS_FILE" ] || {
    echo "$RC_TARGETS_FILE not found — it is the one place the distributed targets and their ADR-0006 tiers are recorded, and every consumer reads it rather than repeating the list." >&2
    return 1
  }
  command -v python3 >/dev/null 2>&1 || {
    echo "python3 not found — it reads release/targets.json. A text scrape would silently return an empty target list, which reads as 'nothing to publish' rather than as a broken tool." >&2
    return 1
  }
  python3 -c '
import json, sys
path, tier = sys.argv[1], sys.argv[2]
with open(path, encoding="utf-8") as handle:
    data = json.load(handle)
names = [t["target"] for t in data["targets"] if not tier or t["tier"] == tier]
if not names:
    sys.exit(f"release/targets.json lists no targets for tier {tier!r}")
print(" ".join(names))
' "$RC_TARGETS_FILE" "$rc__tier"
}

RC_PLAN_FILE=${RC_PLAN_FILE:-"$RC_ROOT/release/plan.json"}

# rc_channel_state <channel> — print `enabled`, or `deferred <version>`.
# Returns non-zero, having explained itself on stderr, when the plan cannot be
# read; the caller must not treat that as "off". A channel this release defers
# needs none of its prerequisites, and a channel nobody could ask about is a
# different answer from one deliberately switched off.
rc_channel_state() {
  [ -f "$RC_PLAN_FILE" ] || {
    echo "$RC_PLAN_FILE not found — it is the one place the channels a release publishes through are recorded, and every consumer reads it rather than assuming." >&2
    return 1
  }
  command -v python3 >/dev/null 2>&1 || {
    echo "python3 not found — it reads release/plan.json. A text scrape would silently report a channel as off, which reads as 'deliberately deferred' rather than as a broken tool." >&2
    return 1
  }
  python3 -c '
import json, sys
path, channel = sys.argv[1], sys.argv[2]
try:
    with open(path, encoding="utf-8") as handle:
        data = json.load(handle)
    rows = [row for row in data["channels"] if row.get("channel") == channel]
except (OSError, ValueError, KeyError, TypeError) as error:
    sys.exit(f"{path} could not be read as a release plan ({error}).")
if len(rows) != 1:
    sys.exit(f"{path} has {len(rows)} rows for the {channel!r} channel; it must have exactly one.")
row = rows[0]
if not isinstance(row.get("enabled"), bool):
    sys.exit(f"{path} does not say whether the {channel!r} channel is enabled.")
if row["enabled"]:
    print("enabled")
else:
    planned = row.get("plannedFor")
    if not isinstance(planned, str) or not planned:
        sys.exit(f"{path} defers the {channel!r} channel without naming the release it is planned for.")
    print(f"deferred {planned}")
' "$RC_PLAN_FILE" "$1"
}

# rc_target_tier <target> — `supported`, `best-effort`, or a refusal.
rc_target_tier() {
  python3 -c '
import json, sys
path, want = sys.argv[1], sys.argv[2]
with open(path, encoding="utf-8") as handle:
    data = json.load(handle)
for entry in data["targets"]:
    if entry["target"] == want:
        print(entry["tier"])
        break
else:
    sys.exit(f"{want!r} is not a target in release/targets.json; add it there rather than special-casing it here")
' "$RC_TARGETS_FILE" "$1"
}

# rc_target_is_required <target> — true for the release-blocking tier.
rc_target_is_required() {
  [ "$(rc_target_tier "$1")" = supported ]
}

# ---------------------------------------------------------------------------
# Selftest harness
#
# Every release script grew its own `note`, and three of them grew more than
# one reporting style. Worse, the common shape
#
#     ( cd … && some_command >/dev/null 2>&1 )
#     note $? "the thing works"
#
# cannot fail: under `set -e` the script has already exited by the time `note`
# runs, so the row prints `ok` on success and nothing at all on failure — no
# FAIL line, no captured diagnostic, no summary. Five such rows existed. The
# helpers below take the command instead of its status, so the status is
# observed rather than inferred, and the command's output is kept and shown.
# ---------------------------------------------------------------------------

# rc_selftest_begin <label> [scratch-dir] — call once, after setting up a temp
# dir. The scratch dir is where captured stdout and stderr land; passing it here
# rather than having each caller assign RC_OUT/RC_ERR keeps those variables
# owned by the one file that reads them. Shellcheck flagged ten assignments as
# unused for exactly that reason — it cannot see through the `.` into this
# library — and silencing ten directives would have been the wrong repair for
# a real smell.
rc_selftest_begin() {
  RC_SELFTEST_LABEL=$1
  RC_FAILURES=0
  rc_capture_into "${2:-${TMPDIR:-/tmp}}"
  echo "$RC_SELFTEST_LABEL --selftest:"
}

# rc_capture_into <dir> — where `rc_run` puts the captured stdout and stderr.
# Non-selftest callers that use `rc_run`/`$RC_OUT`/`$RC_ERR` call this; under
# `set -u` an unset RC_OUT is an immediate failure, so it is not optional.
rc_capture_into() {
  RC_OUT="$1/rc-out.$$"
  RC_ERR="$1/rc-err.$$"
}

# rc_note <status> <name> — record an already-observed status.
rc_note() {
  if [ "$1" -eq 0 ]; then
    echo "  ok   $2"
  else
    echo "  FAIL $2" >&2
    RC_FAILURES=$((RC_FAILURES + 1))
  fi
}

# rc_run <cmd>... — run a command with errexit neutralized, capturing stdout in
# $RC_OUT and stderr in $RC_ERR and leaving the status in $RC_STATUS. Always
# returns 0, so a caller under `set -e` survives to inspect the outcome.
rc_run() {
  RC_STATUS=0
  "$@" >"$RC_OUT" 2>"$RC_ERR" || RC_STATUS=$?
  return 0
}

# rc_expect_status <want> <name> <cmd>... — the workhorse. Runs the command,
# compares its status, and on a mismatch prints the captured stderr, which is
# the part the discarded-output pattern used to throw away.
rc_expect_status() {
  rc__want=$1
  rc__name=$2
  shift 2
  rc_run "$@"
  if [ "$RC_STATUS" -eq "$rc__want" ]; then
    echo "  ok   $rc__name (exit $RC_STATUS)"
    return 0
  fi
  echo "  FAIL $rc__name: expected exit $rc__want, got $RC_STATUS" >&2
  sed 's/^/    /' "$RC_ERR" >&2
  RC_FAILURES=$((RC_FAILURES + 1))
}

# rc_expect_output <want-status> <substring> <name> <cmd>... — status *and* a
# substring of the combined output, for the refusals whose message is the point.
rc_expect_output() {
  rc__want=$1
  rc__needle=$2
  rc__name=$3
  shift 3
  rc_run "$@"
  rc__matched=0
  grep -q -- "$rc__needle" "$RC_ERR" "$RC_OUT" && rc__matched=1
  if [ "$RC_STATUS" -eq "$rc__want" ] && [ "$rc__matched" -eq 1 ]; then
    echo "  ok   $rc__name (exit $RC_STATUS)"
    return 0
  fi
  # Which half failed, not just that one did. A row whose status is right and
  # whose message is wrong is the common case — the code took some *other*
  # refusal path — and reporting only the status sends the reader looking at
  # the exit code, which was never the problem.
  if [ "$RC_STATUS" -ne "$rc__want" ]; then
    echo "  FAIL $rc__name: expected exit $rc__want, got $RC_STATUS" >&2
  else
    echo "  FAIL $rc__name: exit $RC_STATUS was expected, but no output matched '$rc__needle' — the command refused for some other reason" >&2
  fi
  sed 's/^/    /' "$RC_ERR" >&2
  RC_FAILURES=$((RC_FAILURES + 1))
}

# rc_selftest_end <remedy> — exit 1 with a count when anything failed.
rc_selftest_end() {
  if [ "$RC_FAILURES" -ne 0 ]; then
    echo "$RC_SELFTEST_LABEL: --selftest found $RC_FAILURES broken case(s). $1" >&2
    exit 1
  fi
  echo "$RC_SELFTEST_LABEL: --selftest passed"
  exit 0
}

# ---------------------------------------------------------------------------
# The stub cosign
#
# Both verifier selftests fabricate one, and the two copies had already diverged
# in what they assert. The stub's job is not to imitate cosign: it is to prove
# that the caller handed cosign the *pinned* issuer and expression, byte for
# byte, and never a transparency-log bypass. A stub that ignored its arguments
# would stay green while its caller passed a mangled expression — the failure
# that reaches users as "every genuine release is rejected".
#
# rc_write_stub_cosign <bin-dir> <identity-pin> <log-dir>
#
# <identity-pin> is release/identity.pin — the two inert lines a verifier
# actually reads, not release/identity.json. The stub compares what its caller
# passed against the same file the caller was supposed to read, so a verifier
# that quietly used a different pin fails here. Reading it the same way the
# verifier does (one descriptor, `IFS= read -r`) is also what keeps `python3`
# off the selftest path, which is itself part of the release policy.
#   COSIGN_STUB_VERDICT=ok|bad|broken   the verdict for every call
#   COSIGN_STUB_FAIL_ON=<basename>      fail one named blob only
# Writes <log-dir>/cosign-argv and <log-dir>/cosign-blobs.
# ---------------------------------------------------------------------------
rc_write_stub_cosign() {
  rc__bin=$1
  rc__pin=$2
  rc__log=$3
  mkdir -p "$rc__bin" "$rc__log"
  cat > "$rc__bin/cosign" <<STUB
#!/bin/sh
pin='$rc__pin'
log='$rc__log'
printf '%s\n' "\$*" >> "\$log/cosign-argv"
want_issuer=''
want_identity=''
{
  IFS= read -r want_issuer || true
  IFS= read -r want_identity || true
} < "\$pin"
blob=''
got_issuer=''
got_identity=''
got_bundle=''
seen_verify=0
while [ \$# -gt 0 ]; do
  case \$1 in
    verify-blob) seen_verify=1; shift ;;
    --certificate-oidc-issuer) got_issuer=\$2; shift 2 ;;
    --certificate-identity-regexp) got_identity=\$2; shift 2 ;;
    --bundle) got_bundle=\$2; shift 2 ;;
    --insecure-ignore-tlog*)
      echo "stub cosign: called with \$1 — the transparency-log check must never be bypassed" >&2
      exit 90
      ;;
    -*) shift ;;
    *) [ -n "\$blob" ] || blob=\$1; shift ;;
  esac
done
[ "\$seen_verify" -eq 1 ] || { echo "stub cosign: not a verify-blob call" >&2; exit 95; }
[ "\$got_issuer" = "\$want_issuer" ] || {
  echo "stub cosign: issuer '\$got_issuer' is not the pinned '\$want_issuer'" >&2
  exit 91
}
[ "\$got_identity" = "\$want_identity" ] || {
  echo "stub cosign: identity expression '\$got_identity' is not the pinned '\$want_identity'" >&2
  exit 92
}
[ -n "\$got_bundle" ] || { echo "stub cosign: no --bundle was passed" >&2; exit 93; }
[ -f "\$got_bundle" ] || { echo "stub cosign: bundle '\$got_bundle' does not exist" >&2; exit 94; }
printf '%s\n' "\${blob##*/}" >> "\$log/cosign-blobs"
if [ -n "\${COSIGN_STUB_FAIL_ON:-}" ] && [ "\${blob##*/}" = "\$COSIGN_STUB_FAIL_ON" ]; then
  echo "error: no matching signatures: none of the expected identities matched what was in the certificate" >&2
  exit 1
fi
case "\${COSIGN_STUB_VERDICT:-ok}" in
  ok) ;;
  bad)
    echo "error: no matching signatures: none of the expected identities matched what was in the certificate" >&2
    exit 1
    ;;
  broken)
    echo "error: fetching trust root: Get \"https://tuf-repo-cdn.sigstore.dev/\": dial tcp: lookup failed" >&2
    exit 1
    ;;
esac
echo "Verified OK"
exit 0
STUB
  chmod +x "$rc__bin/cosign"
}

# rc_write_stub_uname <dir> <uname-s> <uname-m> — a `uname` first on PATH, so
# the platform branches are driven through the real code rather than inspected.
rc_write_stub_uname() {
  mkdir -p "$1"
  cat > "$1/uname" <<UNAME
#!/bin/sh
case "\$1" in
  -s) echo "$2" ;;
  -m) echo "$3" ;;
  *) echo "$2" ;;
esac
UNAME
  chmod +x "$1/uname"
}
